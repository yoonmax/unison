// Writes supabase/seed.sql from the starting-word list, for people who prefer
// the Supabase CLI or SQL editor over `npm run db:migrate` (which seeds itself).
import { writeFileSync } from "node:fs";
import path from "node:path";
import { STARTING_WORDS } from "../src/lib/game/starting-words";

const rows = [...new Set(STARTING_WORDS)].map((w) => `  ('${w}')`).join(",\n");
const sql = `-- Generated by \`npm run db:seed-sql\`. Do not edit by hand.
insert into unison.starting_words (word) values
${rows}
on conflict (word) do nothing;
`;
const out = path.resolve(import.meta.dirname, "../supabase/seed.sql");
writeFileSync(out, sql);
console.log(`wrote ${STARTING_WORDS.length} words to ${out}`);
